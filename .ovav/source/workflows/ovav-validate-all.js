/**
 * OVAV Validate All Workflow
 *
 * Runs comprehensive F0-F5 validation using native tools:
 *   1. F0: Supply chain, secrets, runtime integrity, network, bootstrap, exfil
 *   2. F1: Systemic validators
 *   3. F2: System paths, config governance, plugins, claims
 *   4. F3: Role surfaces, sandbox, temporal scoping
 *   5. F4: Bash commands, unsafe selectors
 *   6. F5: Gate liberation
 *
 * Uses ovav_check_integrity for filesystem checks and ovav_validate for Go runtime.
 */

export const meta = {
  name: "ovav-validate-all",
  description: "Comprehensive OVAV F0-F5 validation with integrity scoring",
};

export default async function ovavValidateAll(args, { agent, parallel, log }) {
  log("🛡️ OVAV Validate All — comprehensive governance check");

  // Phase 1: Filesystem integrity
  log("📁 Phase 1: Filesystem integrity check");
  const integrity = await agent({
    prompt: `Run the ovav_check_integrity tool and report the results.
Then check for:
1. All governance files exist (.ovav/plan/caps.yaml, .ovav/policy/permission_authority.json, .ovav/laws/)
2. No stale/orphaned files in .ovav/runtime/
3. Plugin files are valid JS (syntax check)
4. Skills have valid frontmatter

Output a structured report with pass/fail for each check.`,
  });

  // Phase 2: Git state
  log("📊 Phase 2: Git state validation");
  const gitState = await agent({
    prompt: `Check git state:
1. Current branch (should be feature/mimocode-full-integration)
2. Last 5 commits (git log --oneline -5)
3. Working tree status (git status --short)
4. No uncommitted governance file changes
5. Protected branch status

Output structured report.`,
  });

  // Phase 3: Plugin validation
  log("🔌 Phase 3: Plugin health check");
  const pluginCheck = await agent({
    prompt: `Verify all OVAV plugins:
1. ovav-governance.js — exists, exports OvavGovernance, has 4 tools
2. ovav-status.js — exists, exports OvavStatus, has 2 tools
3. ovav-monitor.js — exists, exports OVAVMonitor, has 1 tool
4. ovav-security.js — exists, exports OvavSecurity, has 4 hooks
5. package.json has @mimo-ai/plugin dependency
6. node_modules/@mimo-ai/plugin exists

Check each file for syntax errors. Output structured report.`,
  });

  // Phase 4: Skill consistency
  log("📚 Phase 4: Skill reference consistency");
  const skillCheck = await agent({
    prompt: `Verify skill files:
1. .mimocode/skills/ — all SKILL.md files have valid frontmatter
2. All tool references in skills point to actual plugin tools
3. No stale Python references (except documented fallback)
4. clients/opencode/skills/ is in sync with .mimocode/skills/

Grep for "python3" across all SKILL.md files. Output structured report.`,
  });

  // Phase 5: Security hooks
  log("🔒 Phase 5: Security hook verification");
  const securityCheck = await agent({
    prompt: `Verify security hooks:
1. ovav-security.js is loaded (check .mimocode/plugins/)
2. Audit log directory exists (.ovav/runtime/logs/)
3. permission_authority.json has protected_denies.bash array
4. DANGEROUS_PATTERNS in ovav-security.js covers all protected_denies

Output structured report.`,
  });

  // Consolidate
  log("📊 Consolidating results");

  return `
# OVAV Validate All — Complete Report

## Phase 1: Filesystem Integrity
${integrity}

## Phase 2: Git State
${gitState}

## Phase 3: Plugin Health
${pluginCheck}

## Phase 4: Skill Consistency
${skillCheck}

## Phase 5: Security Hooks
${securityCheck}

---
Generated by ovav-validate-all workflow at ${new Date().toISOString()}
`;
}
